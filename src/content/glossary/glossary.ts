export function getGlossaryByTerm(query: string, lang: 'en' | 'te' = 'en'): GlossaryEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return GLOSSARY;
  return GLOSSARY.filter(g => {
    const term = g.term[lang]?.toLowerCase() || '';
    const shortDef = g.shortDefinition[lang]?.toLowerCase() || '';
    const enTerm = g.term.en.toLowerCase();
    const enDef = g.shortDefinition.en.toLowerCase();
    return term.includes(q) || shortDef.includes(q) || enTerm.includes(q) || enDef.includes(q);
  });
}

export function getGlossaryByPillar(pillarId: string): GlossaryEntry[] {
  return GLOSSARY.filter(g => g.pillarId === pillarId);
}

export function getGlossaryById(id: string): GlossaryEntry | undefined {
  return GLOSSARY.find(g => g.id === id);
}

export function getGlossaryBySlug(slug: string): GlossaryEntry | undefined {
  return GLOSSARY.find(g => g.slug === slug);
}
